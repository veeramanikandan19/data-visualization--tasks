import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

df =pd.read_csv("/content/drive/MyDrive/file/StudentsPerformance.csv")
df

df.describe()

df.info()

df.head()

df.tail()

score_columns =['math score','reading score','writing score']

df[score_columns].head()

