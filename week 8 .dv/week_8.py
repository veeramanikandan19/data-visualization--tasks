parental_score = df.groupby('parental level of education')[score_columns].mean()
parental_score
plt.title('average score by parental level of education')
plt.xlabel('parental level of education')
plt.ylabel('average score')
plt.xticks(rotation=45)
plt.legend(title='subject')
plt.show()

sns.scatterplot(
    data=df,
    x='math score',
    y='writing score'
)

plt.title('Math Score vs Writing Score')
plt.xlabel('Math Score')
plt.ylabel('Writing Score')
plt.show()

plt.figure(figsize=(7,5))

sns.scatterplot(
    data=df,
    x='reading score',
    y='writing score'
)

plt.title('Reading Score vs Writing Score')
plt.xlabel('Reading Score')
plt.ylabel('Writing Score')
plt.show()

correlation = df[
    ['math score', 'reading score', 'writing score']
].corr()
print(correlation)

plt.figure(figsize=(7,5))

sns.heatmap(
    correlation,
    annot=True,
    cmap='coolwarm',
    vmin=-1,
    vmax=1
)

plt.title('Correlation Between Student Scores')
plt.show()

print("Math-Reading Correlation:",
      df['math score'].corr(df['reading score']))

print("Math-Writing Correlation:",
      df['math score'].corr(df['writing score']))

