df

sns.set_theme(style="whitegrid")
plt.rcParams.update({"figure.autolayout": True})

print("--- 1. Loading and Inspecting Dataset ---")
file_path = "/content/drive/MyDrive/file/kc_house_data.csv"
df = pd.read_csv(file_path)

print(f"Total Records (Rows): {df.shape[0]}")
print(f"Total Columns: {df.shape[1]}")
print("\nFirst 3 rows:")
display(df.head(3))

print("\nDataset Info & Missing Values:")
df.info()
print("\nMissing values per column:\n", df.isnull().sum())
print(
    f"Duplicate rows count: {df.duplicated().sum()}"
)

print("\n--- 2. Data Cleaning & Pre-processing ---")

df["date_parsed"] = pd.to_datetime(df["date"], format="%Y%m%dT%H%M%S")

print(f"Properties with 0 bedrooms: {(df['bedrooms'] == 0).sum()}")
print(f"Properties with 0 bathrooms: {(df['bathrooms'] == 0).sum()}")

if 33 in df["bedrooms"].values:
    print("Note: Found the 33-bedroom outlier row. Keeping or flagging as needed.")

print("\n--- 3. Temporal Feature Engineering ---")

df["sale_year"] = df["date_parsed"].dt.year
df["sale_month"] = df["date_parsed"].dt.month

df["property_age"] = df["sale_year"] - df["yr_built"]

df["is_renovated"] = df["yr_renovated"].apply(
    lambda x: 1 if x > 0 else 0
)

df["years_since_renovation"] = df.apply(
    lambda row: (
        row["sale_year"] - row["yr_renovated"]
        if row["yr_renovated"] > 0
        else row["property_age"]
    ),
    axis=1,
)
print("\n--- 4. Price per Square Foot Analysis ---")

df["sqft_living"] = df["sqft_living"].replace(0, np.nan)
df["sqft_lot"] = df["sqft_lot"].replace(0, np.nan)

df["price_per_sqft_living"] = df["price"] / df["sqft_living"]
df["price_per_sqft_lot"] = df["price"] / df["sqft_lot"]

df.drop(columns=["date_parsed"], inplace=True)

print("\n--- 5. Outlier Detection using IQR Method ---")

def print_iqr_bounds(series, name):
  Q1 = series.quantile(0.25)
  Q3 = series.quantile(0.75)
  IQR = Q3 - Q1
  lower_bound = Q1 - 1.5 * IQR
  upper_bound = Q3 + 1.5 * IQR
  print(
      f"{name} -> Q1: {Q1:.2f}, Q3: {Q3:.2f}, IQR: {IQR:.2f} | Upper Bound:"
      f" {upper_bound:.2f}"
  )

df["date_dt"] = pd.to_datetime(df["date"], format="%Y%m%dT%H%M%S")
df["sale_year"] = df["date_dt"].dt.year
df["sale_month"] = df["date_dt"].dt.month
df["sale_day"] = df["date_dt"].dt.day
df["sale_hour"] = df["date_dt"].dt.hour

df.drop(columns=["date_dt"], inplace=True)
df[["sale_year", "sale_month", "sale_day", "sale_hour"]].head()

df["bedrooms"] = df["bedrooms"].replace(0, df["bedrooms"].median())
df["bathrooms"] = df["bathrooms"].replace(0, df["bathrooms"].median())

df["property_age"] = df["sale_year"] - df["yr_built"]

df["is_renovated"] = df["yr_renovated"].apply(lambda x: 1 if x > 0 else 0)

df["years_since_renovation"] = df.apply(
    lambda row: row["sale_year"] - row["yr_renovated"]
    if row["yr_renovated"] > 0
    else row["property_age"],
    axis=1,
)

df["price_per_sqft_living"] = df["price"] / df["sqft_living"]
df["price_per_sqft_lot"] = df["price"] / df["sqft_lot"]

Q1 = df["price"].quantile(0.25)
Q3 = df["price"].quantile(0.75)
IQR = Q3 - Q1
lower_bound = Q1 - 1.5 * IQR
upper_bound = Q3 + 1.5 * IQR

outliers = df[(df["price"] < lower_bound) | (df["price"] > upper_bound)]
print(f"Number of price outliers identified: {len(outliers)}")

plt.figure(figsize=(8, 4))
sns.boxplot(x=df["price"])
plt.title("Box Plot of House Prices (Outlier Detection)")
plt.show()